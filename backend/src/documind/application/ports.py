"""Ports (interfaces) the application layer depends on. Adapters live in infrastructure."""

from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import BinaryIO, Protocol
from uuid import UUID


class PasswordHasher(Protocol):
    async def hash(self, password: str) -> str: ...

    async def verify(self, password_hash: str, password: str) -> bool: ...

    def needs_rehash(self, password_hash: str) -> bool: ...

    async def verify_dummy(self, password: str) -> None:
        """Spend the same time as a real verification (for unknown accounts)."""
        ...


@dataclass(frozen=True, slots=True)
class IssuedAccessToken:
    token: str
    expires_in: int


@dataclass(frozen=True, slots=True)
class AccessTokenClaims:
    user_id: UUID
    auth_version: int
    # When the user last completed a 2FA check, if this token was issued by step-up.
    mfa_verified_at: datetime | None = None


class AccessTokenService(Protocol):
    def issue(
        self, user_id: UUID, auth_version: int, *, mfa_verified_at: datetime | None = None
    ) -> IssuedAccessToken: ...

    def decode(self, token: str) -> AccessTokenClaims:
        """Raise AuthenticationError if the token is invalid or expired."""
        ...


@dataclass(frozen=True, slots=True)
class EmailMessage:
    to: str
    subject: str
    text: str
    html: str


class EmailSender(Protocol):
    async def send(self, message: EmailMessage) -> None: ...


class RateLimiter(Protocol):
    async def hit(self, scope: str, identifier: str, limit: int, window_seconds: int) -> None:
        """Count one request; raise RateLimitedError when over the limit."""
        ...


# --------------------------------------------------------------------------- #
# Object storage
# --------------------------------------------------------------------------- #


class ObjectNotFoundError(Exception):
    """The requested object does not exist in storage."""


@dataclass(frozen=True, slots=True)
class ObjectMetadata:
    key: str
    size: int
    content_type: str | None
    etag: str | None
    metadata: dict[str, str]


class ObjectStorageProvider(Protocol):
    """Private object storage. Keys are always generated by the application."""

    async def upload(
        self, key: str, file: BinaryIO, *, content_type: str, metadata: dict[str, str] | None = None
    ) -> None: ...

    async def download_to(self, key: str, file: BinaryIO) -> None: ...

    async def delete(self, key: str) -> None:
        """Idempotent: deleting a missing object is not an error."""
        ...

    async def get_metadata(self, key: str) -> ObjectMetadata:
        """Raise ObjectNotFoundError if the object doesn't exist."""
        ...

    def generate_signed_url(
        self, key: str, *, expires_in: int, download_filename: str, content_type: str
    ) -> str:
        """A short-lived GET URL that always downloads as an attachment."""
        ...


# --------------------------------------------------------------------------- #
# Malware scanning
# --------------------------------------------------------------------------- #


@dataclass(frozen=True, slots=True)
class ScanResult:
    clean: bool
    scanner: str
    signature: str | None = None


class MalwareScanner(Protocol):
    async def scan(self, file: BinaryIO) -> ScanResult:
        """Raise ScannerUnavailableError if scanning is configured but can't run."""
        ...


class ScannerUnavailableError(Exception):
    pass
