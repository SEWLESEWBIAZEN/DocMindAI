class ObjectNotFoundError(Exception):
    """The requested object does not exist in storage."""


@dataclass(frozen=True, slots=True)
class ObjectMetadata:
    key: str
    size: int
    content_type: str | None
    etag: str | None
    metadata: dict[str, str]


class ObjectStorageProvider(Protocol):
    """Private object storage. Keys are always generated by the application."""

    async def upload(
        self, key: str, file: BinaryIO, *, content_type: str, metadata: dict[str, str] | None = None
    ) -> None: ...

    async def download_to(self, key: str, file: BinaryIO) -> None: ...

    async def delete(self, key: str) -> None:
        """Idempotent: deleting a missing object is not an error."""
        ...

    async def get_metadata(self, key: str) -> ObjectMetadata:
        """Raise ObjectNotFoundError if the object doesn't exist."""
        ...

    def generate_signed_url(
        self, key: str, *, expires_in: int, download_filename: str, content_type: str
    ) -> str:
        """A short-lived GET URL that always downloads as an attachment."""
        ...


